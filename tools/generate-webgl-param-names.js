/**
 * Generates src/embeddedFrontend/react/shared/webglParameterNames.ts.
 *
 * Parses the WebGL / WebGL2 rendering-context interfaces from TypeScript's
 * bundled `lib.dom.d.ts` and extracts each method's parameter names. The result
 * is a map of `functionName -> string[][]` where each inner array is the
 * parameter-name list for one overload (sorted by arity).
 *
 * This powers the "show argument names" feature in the command-detail panel
 * (GitHub issue #56). Re-run whenever the TypeScript dependency is upgraded:
 *
 *     node tools/generate-webgl-param-names.js
 */
"use strict";

const ts = require("typescript");
const fs = require("fs");
const path = require("path");

// The WebGL context is split across these interfaces in lib.dom.d.ts. The
// "*Overloads" interfaces hold the multi-signature methods (bufferData, etc.).
const TARGET_INTERFACES = new Set([
    "WebGLRenderingContextBase",
    "WebGLRenderingContextOverloads",
    "WebGL2RenderingContextBase",
    "WebGL2RenderingContextOverloads",
]);

function main() {
    const libPath = path.join(path.dirname(require.resolve("typescript")), "lib.dom.d.ts");
    if (!fs.existsSync(libPath)) {
        throw new Error("Could not find lib.dom.d.ts at " + libPath);
    }

    const source = fs.readFileSync(libPath, "utf8");
    const sourceFile = ts.createSourceFile("lib.dom.d.ts", source, ts.ScriptTarget.Latest, true);

    /** @type {{ [name: string]: string[][] }} */
    const map = {};

    const addOverload = (name, params) => {
        if (!map[name]) {
            map[name] = [];
        }
        const signature = params.join(",");
        if (!map[name].some((existing) => existing.join(",") === signature)) {
            map[name].push(params);
        }
    };

    sourceFile.forEachChild((node) => {
        if (!ts.isInterfaceDeclaration(node) || !TARGET_INTERFACES.has(node.name.text)) {
            return;
        }
        node.members.forEach((member) => {
            if (!ts.isMethodSignature(member) || !member.name || !ts.isIdentifier(member.name)) {
                return;
            }
            const functionName = member.name.text;
            const params = member.parameters
                .filter((p) => p.name && ts.isIdentifier(p.name))
                .map((p) => p.name.text);
            addOverload(functionName, params);
        });
    });

    // Deterministic ordering: overloads by arity (then lexical), keys alphabetically.
    for (const key of Object.keys(map)) {
        map[key].sort((a, b) => (a.length - b.length) || a.join(",").localeCompare(b.join(",")));
    }
    const keys = Object.keys(map).sort();

    let out = "";
    out += "/* tslint:disable */\n";
    out += "// AUTO-GENERATED FILE - DO NOT EDIT BY HAND.\n";
    out += "// Generated by tools/generate-webgl-param-names.js from TypeScript's lib.dom.d.ts.\n";
    out += "// Run \"node tools/generate-webgl-param-names.js\" to regenerate.\n";
    out += "//\n";
    out += "// Maps each WebGL / WebGL2 method name to its parameter-name lists (one per\n";
    out += "// overload, sorted by arity). Used to label command arguments in the result view.\n\n";
    out += "export const webglParameterNames: { [functionName: string]: string[][] } = {\n";
    for (const key of keys) {
        const overloads = map[key]
            .map((names) => "[" + names.map((n) => JSON.stringify(n)).join(", ") + "]")
            .join(", ");
        out += "    " + JSON.stringify(key) + ": [" + overloads + "],\n";
    }
    out += "};\n";

    const outPath = path.join(__dirname, "..", "src", "embeddedFrontend", "react", "shared", "webglParameterNames.ts");
    fs.writeFileSync(outPath, out, "utf8");

    console.log("Wrote " + keys.length + " functions to " + path.relative(path.join(__dirname, ".."), outPath));
}

main();
